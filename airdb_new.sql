CREATE DATABASE IF NOT EXISTS airdatabase
DEFAULT CHARACTER SET utf8mb4 
DEFAULT COLLATE utf8mb4_general_ci;
USE airdatabase;

-- 2. 处理外键依赖：先删依赖Flights的Orders表，再删Flights（关键！）
DROP TABLE IF EXISTS Orders;
DROP TABLE IF EXISTS Flights;
DROP TABLE IF EXISTS Users; -- 若Users表也存在依赖，一并按顺序删除

-- 3. 重新创建表（确保表结构无语法错误）
-- 创建用户表（供Orders表外键关联）
CREATE TABLE Users (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '用户ID',
    user_name VARCHAR(50) NOT NULL UNIQUE COMMENT '用户名',
    user_password VARCHAR(50) NOT NULL COMMENT '密码',
    real_name VARCHAR(50) NOT NULL COMMENT '真实姓名', -- 新增：存储注册时的realName
    real_id VARCHAR(20) NOT NULL UNIQUE COMMENT '身份证号', -- 新增：存储注册时的idCard
    role INT DEFAULT 0 COMMENT '角色：0-普通用户，1-管理员'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 创建航班表（核心存储航班数据）
CREATE TABLE Flights (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '航班ID',
    flight_id VARCHAR(30) NOT NULL UNIQUE COMMENT '航班号',
    depart_city VARCHAR(30) NOT NULL COMMENT '出发城市',
    depart_time DATETIME NOT NULL COMMENT '出发时间',
    arrive_city VARCHAR(30) NOT NULL COMMENT '到达城市',
    arrive_time DATETIME NOT NULL COMMENT '到达时间',
    total_seats INT NOT NULL COMMENT '总座位数',
    remaining_seats INT NOT NULL COMMENT '剩余座位数',
    price INT NOT NULL COMMENT '票价（元）'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 创建订单表（关联Users和Flights的外键）
CREATE TABLE Orders (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '订单ID',
    user_id INT NOT NULL COMMENT '关联用户ID',
    flight_id INT NOT NULL COMMENT '关联航班ID',
    order_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '下单时间',
    seat_num VARCHAR(5) NOT NULL COMMENT '座位号',
    status TINYINT DEFAULT 0 COMMENT '订单状态：0-待支付，1-已支付，2-已取消',
    -- 外键约束：删除用户/航班时自动删除关联订单
    FOREIGN KEY (user_id) REFERENCES Users(id) ON DELETE CASCADE,
    FOREIGN KEY (flight_id) REFERENCES Flights(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

